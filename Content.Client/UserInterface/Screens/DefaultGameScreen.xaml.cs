using System.Numerics;
using Content.Client.UserInterface.Systems.Chat.Widgets;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.UserInterface.Screens;

[GenerateTypedNameReferences]
public sealed partial class DefaultGameScreen : InGameScreen
{
    public DefaultGameScreen()
    {
        RobustXamlLoader.Load(this);

        AutoscaleMaxResolution = new Vector2i(1080, 770);

        SetAnchorPreset(MainViewport, LayoutPreset.Wide);
        SetAnchorPreset(ViewportContainer, LayoutPreset.Wide);
        SetAnchorAndMarginPreset(TopLeft, LayoutPreset.TopLeft, margin: 10);
        SetAnchorAndMarginPreset(Ghost, LayoutPreset.BottomWide, margin: 80);

        SetAnchorPreset(Inventory, LayoutPreset.LeftWide);
        LayoutContainer.SetGrowHorizontal(Inventory, LayoutContainer.GrowDirection.End);
        LayoutContainer.SetGrowVertical(Inventory, LayoutContainer.GrowDirection.Both);
        SetMarginLeft(Inventory, 0);
        SetMarginTop(Inventory, 0);
        SetMarginBottom(Inventory, 0);

        SetAnchorPreset(Hotbar, LayoutPreset.TopLeft);
        LayoutContainer.SetGrowHorizontal(Hotbar, LayoutContainer.GrowDirection.End);
        LayoutContainer.SetGrowVertical(Hotbar, LayoutContainer.GrowDirection.End);
        SetMarginLeft(Hotbar, 0);
        SetMarginRight(Hotbar, 0);
        SetMarginBottom(Hotbar, 0);

        SetAnchorAndMarginPreset(Chat, LayoutPreset.TopRight, margin: 10);
        SetAnchorAndMarginPreset(Alerts, LayoutPreset.TopRight, margin: 10);
        SetAnchorAndMarginPreset(Targeting, LayoutPreset.BottomRight, margin: 5);

        UpdateLeftHud();

        Chat.OnResized += ChatOnResized;
        Chat.OnChatResizeFinish += ChatOnResizeFinish;
        MainViewport.OnResized += ResizeActionContainer;
        MainViewport.OnResized += ResizeAlertsContainer;
        MainViewport.OnResized += UpdateLeftHud;
        OnResized += UpdateLeftHud;
        Inventory.OnResized += ResizeActionContainer;
    }

    private void UpdateLeftHud()
    {
        var screenHeight = Size.Y > 0 ? Size.Y : (MainViewport.Size.Y > 0 ? MainViewport.Size.Y : 1080f);
        var slotSize = MathF.Floor(screenHeight / 15f);
        if (slotSize <= 0)
            slotSize = 96f;
        var panelWidth = slotSize * 3f;

        SetMarginRight(Inventory, panelWidth);
        SetMarginTop(Hotbar, slotSize * 4f - 5f);
        LayoutContainer.SetMarginLeft(TopLeft, panelWidth + 10f);

        Inventory.UpdateSlotSize(slotSize);
        Hotbar.UpdateSlotSize(slotSize);
    }

    private void ResizeActionContainer()
    {
        float indent = TopBar.Size.Y + 40;
        Actions.ActionsContainer.MaxGridHeight = MainViewport.Size.Y - indent;
    }

    private void ResizeAlertsContainer()
    {
        float indent = Chat.Size.Y + Targeting.Size.Y + 120;
        Alerts.AlertContainer.MaxGridHeight = Math.Max(MainViewport.Size.Y - indent, 1);
    }

    private void ChatOnResizeFinish(Vector2 _)
    {
        var marginBottom = Chat.GetValue<float>(MarginBottomProperty);
        var marginLeft = Chat.GetValue<float>(MarginLeftProperty);
        OnChatResized?.Invoke(new Vector2(marginBottom, marginLeft));
    }

    private void ChatOnResized()
    {
        var marginBottom = Chat.GetValue<float>(MarginBottomProperty);
        var marginLeft = Chat.GetValue<float>(MarginLeftProperty);
        SetChatSize(new Vector2(marginBottom, marginLeft));
    }

    public override ChatBox ChatBox => Chat;

    public override void SetChatSize(Vector2 size)
    {
        SetMarginBottom(Chat, size.X);
        SetMarginLeft(Chat, size.Y);
        SetMarginTop(Alerts, size.X);
    }
}
