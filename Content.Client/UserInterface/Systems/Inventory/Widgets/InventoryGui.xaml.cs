using System;
using System.Collections.Generic;
using System.IO;
using Content.Client.UserInterface.Systems.Inventory;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Timing;

namespace Content.Client.UserInterface.Systems.Inventory.Widgets;

[GenerateTypedNameReferences]
public sealed partial class InventoryGui : UIWidget
{
    private Texture? _combatOffTex;
    private readonly List<Texture> _combatActiveFrames = new();
    private bool _inCombat;
    private float _combatFrameTimer;
    private float _nextCombatInterval = 0.08f;
    private int _currentCombatFrameIndex;

    private Texture? _sprintOffTex;
    private readonly List<Texture> _sprintActiveFrames = new();
    private bool _isSprinting;
    private float _sprintFrameTimer;
    private float _nextSprintInterval = 0.08f;
    private int _currentSprintFrameIndex;

    private readonly System.Random _random = new();

    public InventoryGui()
    {
        RobustXamlLoader.Load(this);

        var resCache = IoCManager.Resolve<IResourceCache>();
        if (resCache.TryGetResource<TextureResource>("/Textures/Interface/Nano/lfwb_left_hud_bg.png", out var hudTex))
        {
            var hudBg = new StyleBoxTexture
            {
                Texture = hudTex.Texture,
                Mode = StyleBoxTexture.StretchMode.Stretch,
            };
            LeftHudPanel.PanelOverride = hudBg;
        }

        if (resCache.TryGetResource<TextureResource>("/Textures/Interface/NigWeb/cmbt0.png", out var cmbtOffTex) ||
            resCache.TryGetResource<TextureResource>("/Textures/Interface/Default/cmbt0.png", out cmbtOffTex))
        {
            _combatOffTex = cmbtOffTex.Texture;
        }

        string[] cmbtFrameFiles =
        [
            "cmbt1_frame0.png",
            "cmbt1_frame1.png",
            "cmbt1_frame2.png",
        ];
        string[] cmbtAltFrameFiles =
        [
            "cmbt1_0.png",
            "cmbt1_1.png",
            "cmbt1_2.png",
        ];

        for (var i = 0; i < cmbtFrameFiles.Length; i++)
        {
            if (resCache.TryGetResource<TextureResource>($"/Textures/Interface/NigWeb/{cmbtFrameFiles[i]}", out var fTex) ||
                resCache.TryGetResource<TextureResource>($"/Textures/Interface/NigWeb/{cmbtAltFrameFiles[i]}", out fTex) ||
                resCache.TryGetResource<TextureResource>($"/Textures/Interface/Default/{cmbtFrameFiles[i]}", out fTex) ||
                resCache.TryGetResource<TextureResource>($"/Textures/Interface/Default/{cmbtAltFrameFiles[i]}", out fTex))
            {
                _combatActiveFrames.Add(fTex.Texture);
            }
        }

        if (resCache.TryGetResource<TextureResource>("/Textures/Interface/NigWeb/sprint0.png", out var sprintOffTex) ||
            resCache.TryGetResource<TextureResource>("/Textures/Interface/Default/sprint0.png", out sprintOffTex))
        {
            _sprintOffTex = sprintOffTex.Texture;
        }

        string[] sprintFrameFiles =
        [
            "sprint1_frame0.png",
            "sprint1_frame1.png",
            "sprint1_frame2.png",
        ];
        string[] sprintAltFrameFiles =
        [
            "sprint1_0.png",
            "sprint1_1.png",
            "sprint1_2.png",
        ];

        for (var i = 0; i < sprintFrameFiles.Length; i++)
        {
            if (resCache.TryGetResource<TextureResource>($"/Textures/Interface/NigWeb/{sprintFrameFiles[i]}", out var fTex) ||
                resCache.TryGetResource<TextureResource>($"/Textures/Interface/NigWeb/{sprintAltFrameFiles[i]}", out fTex) ||
                resCache.TryGetResource<TextureResource>($"/Textures/Interface/Default/{sprintFrameFiles[i]}", out fTex) ||
                resCache.TryGetResource<TextureResource>($"/Textures/Interface/Default/{sprintAltFrameFiles[i]}", out fTex))
            {
                _sprintActiveFrames.Add(fTex.Texture);
            }
        }

        if (_combatOffTex != null)
            CombatButton.TextureNormal = _combatOffTex;

        if (_sprintOffTex != null)
            SprintButton.TextureNormal = _sprintOffTex;

        CombatButton.ToolTip = "Боевой режим [1]";
        SprintButton.ToolTip = "Спринт [Space]";

        var inventoryUIController = UserInterfaceManager.GetUIController<InventoryUIController>();
        inventoryUIController.RegisterInventoryBarContainer(InventoryHotbar);

        LayoutContainer.SetGrowHorizontal(this, LayoutContainer.GrowDirection.End);
        LayoutContainer.SetGrowVertical(this, LayoutContainer.GrowDirection.End);
    }

    public void SetCombatModeActive(bool inCombat)
    {
        _inCombat = inCombat;
        if (!_inCombat)
        {
            if (_combatOffTex != null)
                CombatButton.TextureNormal = _combatOffTex;
        }
        else if (_combatActiveFrames.Count > 0)
        {
            _currentCombatFrameIndex = _random.Next(_combatActiveFrames.Count);
            CombatButton.TextureNormal = _combatActiveFrames[_currentCombatFrameIndex];
            _combatFrameTimer = 0f;
            _nextCombatInterval = 0.04f + (float)_random.NextDouble() * 0.10f;
        }
    }

    public void SetSprintActive(bool isSprinting)
    {
        _isSprinting = isSprinting;
        if (!_isSprinting)
        {
            if (_sprintOffTex != null)
                SprintButton.TextureNormal = _sprintOffTex;
        }
        else if (_sprintActiveFrames.Count > 0)
        {
            _currentSprintFrameIndex = _random.Next(_sprintActiveFrames.Count);
            SprintButton.TextureNormal = _sprintActiveFrames[_currentSprintFrameIndex];
            _sprintFrameTimer = 0f;
            _nextSprintInterval = 0.04f + (float)_random.NextDouble() * 0.10f;
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_inCombat && _combatActiveFrames.Count > 0)
        {
            _combatFrameTimer += args.DeltaSeconds;
            if (_combatFrameTimer >= _nextCombatInterval)
            {
                _combatFrameTimer = 0f;
                _nextCombatInterval = 0.04f + (float)_random.NextDouble() * 0.10f;

                var nextIndex = _random.Next(_combatActiveFrames.Count);
                if (nextIndex == _currentCombatFrameIndex && _combatActiveFrames.Count > 1)
                    nextIndex = (nextIndex + 1) % _combatActiveFrames.Count;

                _currentCombatFrameIndex = nextIndex;
                CombatButton.TextureNormal = _combatActiveFrames[_currentCombatFrameIndex];
            }
        }

        if (_isSprinting && _sprintActiveFrames.Count > 0)
        {
            _sprintFrameTimer += args.DeltaSeconds;
            if (_sprintFrameTimer >= _nextSprintInterval)
            {
                _sprintFrameTimer = 0f;
                _nextSprintInterval = 0.04f + (float)_random.NextDouble() * 0.10f;

                var nextIndex = _random.Next(_sprintActiveFrames.Count);
                if (nextIndex == _currentSprintFrameIndex && _sprintActiveFrames.Count > 1)
                    nextIndex = (nextIndex + 1) % _sprintActiveFrames.Count;

                _currentSprintFrameIndex = nextIndex;
                SprintButton.TextureNormal = _sprintActiveFrames[_currentSprintFrameIndex];
            }
        }
    }

    public void UpdateSlotSize(float slotSize)
    {
        var panelWidth = slotSize * 3f;
        InventoryHotbar.HSeparationOverride = 0;
        InventoryHotbar.VSeparationOverride = 0;
        SetWidth = panelWidth;
        MinWidth = panelWidth;
        MaxWidth = panelWidth;
        LeftHudPanel.MinWidth = panelWidth;
        LeftHudPanel.MaxWidth = panelWidth;
        LeftHudPanel.MinHeight = slotSize * 15f;
        InventoryHotbar.MinWidth = panelWidth;
        InventoryHotbar.MaxWidth = panelWidth;
        InventoryHotbar.MinHeight = slotSize * 15f;

        CombatButton.MinSize = new System.Numerics.Vector2(slotSize, slotSize);
        CombatButton.SetSize = new System.Numerics.Vector2(slotSize, slotSize);
        BottomSpacer.MinSize = new System.Numerics.Vector2(slotSize, slotSize);
        BottomSpacer.SetSize = new System.Numerics.Vector2(slotSize, slotSize);
        SprintButton.MinSize = new System.Numerics.Vector2(slotSize, slotSize);
        SprintButton.SetSize = new System.Numerics.Vector2(slotSize, slotSize);

        foreach (var child in InventoryHotbar.Children)
        {
            if (child is Content.Client.UserInterface.Controls.SlotControl slot)
            {
                slot.SetButtonSize(slotSize);
            }
            else
            {
                child.MinSize = new System.Numerics.Vector2(slotSize, slotSize);
                child.SetSize = new System.Numerics.Vector2(slotSize, slotSize);
            }
        }
    }
}
